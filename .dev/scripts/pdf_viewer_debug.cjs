const {chromium}=require('playwright')
;(async()=>{
 const browser=await chromium.launch({headless:true}),page=await browser.newPage()
 page.on('console',m=>console.log(m.type(),m.text()))
 page.on('pageerror',e=>console.log('pageerror',e.message))
 page.on('response',r=>{if(/\.mjs|\.wasm|\.pfb|PdfPreview/.test(r.url()))console.log(r.status(),r.headers()['content-type'],r.url())})
 await page.goto('http://127.0.0.1/#/files')
 await page.getByRole('button',{name:/^Договор_/}).click()
 await page.waitForTimeout(3000)
 console.log((await page.locator('body').innerText()).slice(-1600))
 await browser.close()
})().catch(e=>{console.error(e);process.exitCode=1})
