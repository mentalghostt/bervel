const {test}=require('node:test')
const {assert,path,createState,fixture,browser,base}=require('./frontend-presales-fixtures.cjs')
const directory=path.resolve(process.env.BERVEL_TEST_ARTIFACT_ROOT||'.dev/local/presales-settings-popup-2026-11-10')

for(const width of [1440,390]){
 test('settings use the radar dialog and preserve the selected revision at '+width,()=>browser(width,async page=>{
  await page.setViewportSize({width,height:width===390?844:1000})
  const state=createState();await fixture(page,state)
  const url=base+'/#/presales?request=request-1&revision=revision-1'
  await page.goto(url);await page.getByTestId('presales-score').waitFor()
  const opener=page.getByRole('button',{name:'Настройки пресейла',exact:true})
  await opener.waitFor({timeout:1000});await opener.click()
  const dialog=page.getByRole('dialog',{name:'Настройки пресейла',exact:true})
  await dialog.waitFor();assert.equal(page.url(),url)
  assert.ok(await dialog.evaluate(el=>el.matches('dialog.workspace-dialog:not(.wide)')))
  await dialog.getByLabel('Контакты продавца').fill('sales@bervel.test')
  await dialog.getByLabel('Условия КП').fill('Самовывоз')
  await dialog.getByRole('button',{name:'Сохранить настройки',exact:true}).click()
  await dialog.getByRole('status').filter({hasText:'Настройки сохранены'}).waitFor()
  assert.equal(state.writes.length,1)
  assert.deepEqual(state.writes[0].body.settings,{target_margin_percent:'50',special_min_margin_percent:'70',seller_contacts:'sales@bervel.test',offer_terms:'Самовывоз'})
  await page.screenshot({path:path.join(directory,'popup-'+width+'.png'),fullPage:true,animations:'disabled'})
  await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'})
  assert.equal(page.url(),url);assert.equal(await opener.evaluate(el=>el===document.activeElement),true)
  assert.equal(await page.getByTestId('presales-score').innerText(),'0 / 100')
  await opener.click();await dialog.getByLabel('Контакты продавца').waitFor()
  assert.equal(await dialog.getByLabel('Контакты продавца').inputValue(),'sales@bervel.test')
  const close=dialog.getByRole('button',{name:'Закрыть диалог',exact:true})
  await close.focus();await page.keyboard.press('Shift+Tab')
  assert.equal(await dialog.getByRole('button',{name:'Сохранить настройки',exact:true}).evaluate(el=>el===document.activeElement),true)
  await page.keyboard.press('Tab');assert.equal(await close.evaluate(el=>el===document.activeElement),true)
  await close.click();assert.equal(page.url(),url)
 }))
}
