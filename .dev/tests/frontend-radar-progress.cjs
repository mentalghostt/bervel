const {test}=require('node:test')
const assert=require('node:assert/strict')
test('Фазы и подтверждённые счётчики обновления',async()=>{
 const {radarRefreshStatus:status}=await import('../../frontend/src/radarRefreshStatus.ts')
 const run=(phase,checkpoint={})=>({data:{state:'running',phase,checkpoint}})
 assert.equal(status(run('search')),'Поиск тендеров')
 assert.equal(status(run('ranking',{ranking_completed:64,ranking_total:2774})),'Оценка первичной информации: 64 из 2 774')
 assert.equal(status(run('ranking')),'Оценка первичной информации')
 assert.equal(status(run('details')),'Подтягиваю детали тендеров')
 assert.equal(status(run('analysis',{analysis_completed:7,analysis_total:200})),'Анализирую детали тендеров: 7 из 200')
 assert.equal(status(run('rating')),'Рассчитываю оценку ИИ')
 assert.equal(status({data:{state:'queued',phase:'queued'}}),'Ожидаю начала обновления')
 assert.equal(status({data:{state:'running',phase:'ranking',stop_requested:true}}),'Останавливаем обновление…')
 assert.equal(status({data:{state:'complete',phase:'complete'}}),'База сохранена')
 assert.equal(status({data:{state:'failed',phase:'failed',error:{code:'SOURCE_REQUEST_OUTCOME_UNKNOWN'}}}),'Обновление завершилось ошибкой')
})
