from typing import Any, Callable, ContextManager, Protocol
from uuid import UUID

from bervel.core.models import ActorContext, ArtifactRef, RegisterArtifact, StoredObject


class ObjectStore(Protocol):
    def put(self, content: bytes) -> StoredObject: ...
    def read(self, object_ref: str) -> bytes: ...
    def delete(self, object_ref: str) -> None: ...


class ArtifactRepository(Protocol):
    def original_mutation(self) -> ContextManager[None]: ...
    def register_artifact(self, actor: ActorContext, command: RegisterArtifact, store: Callable[[bytes], StoredObject]) -> ArtifactRef: ...
    def read_artifact(self, actor: ActorContext, ref: ArtifactRef) -> dict[str, Any]: ...
    def list_artifacts(self, actor: ActorContext, cursor: int, limit: int) -> dict[str, Any]: ...
    def delete_artifact(self, actor: ActorContext, artifact_id: UUID) -> list[str]: ...
    def object_is_referenced(self, object_ref: str) -> bool: ...
    def finish_object_deletion(self, artifact_id: UUID, object_ref: str) -> None: ...
    def pending_deletions(self) -> list[tuple[UUID, str]]: ...
    def set_usage_role(self, actor: ActorContext, artifact_id: UUID, usage_role: str) -> dict[str, Any]: ...
