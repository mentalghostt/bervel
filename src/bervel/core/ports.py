from typing import Any, Protocol
from uuid import UUID

from .models import (ActorContext, ArtifactRevisionRef, RegisterArtifact, StoredObject,
                     DatasetRevisionRef, ExtractArtifact, ExtractionResult)
from .process_models import EngineExecution, WorkflowDefinition


class ObjectStore(Protocol):
    def put(self, content: bytes) -> StoredObject: ...
    def read(self, object_ref: str) -> bytes: ...


class ArtifactRepository(Protocol):
    def register_artifact(self, actor: ActorContext, command: RegisterArtifact, stored: StoredObject) -> ArtifactRevisionRef: ...
    def read_artifact(self, actor: ActorContext, ref: ArtifactRevisionRef) -> dict[str, Any]: ...
    def artifact_history(self, actor: ActorContext, artifact_id: UUID) -> dict[str, Any]: ...


class DatasetRepository(Protocol):
    def publish_extraction(self, actor: ActorContext, command: ExtractArtifact, result: ExtractionResult,
                           producer: dict[str, str]) -> DatasetRevisionRef: ...
    def read_dataset(self, actor: ActorContext, ref: DatasetRevisionRef) -> dict[str, Any]: ...
    def read_records(self, actor: ActorContext, ref: DatasetRevisionRef, cursor: int, limit: int) -> dict[str, Any]: ...


class WorkflowEngine(Protocol):
    def describe(self) -> WorkflowDefinition: ...
    def start(self, process_id: str, invocation_token: str) -> None: ...
    def execution(self, execution_id: str) -> EngineExecution: ...
    def retry(self, execution_id: str) -> EngineExecution: ...
    def find(self, workflow_id: str, process_id: str, retry_of: str | None = None) -> list[EngineExecution]: ...


class ProcessRepository(Protocol):
    def lookup_start(self, actor, command) -> dict | None: ...
    def create(self, actor, command, workflow, invocation_token, producer) -> tuple[dict, bool]: ...
    def read(self, actor, run_id) -> dict: ...
    def list(self, actor, state=None, cursor=0, limit=20) -> dict: ...
    def claim(self, run_id, invocation_token, execution): ...
    def complete(self, lease, result, producer) -> DatasetRevisionRef: ...
    def fail(self, lease, code) -> None: ...
    def dispatch_unknown(self, run_id, number) -> None: ...
    def observe(self, actor, run_id, execution) -> dict: ...
    def lookup_recovery(self, actor, run_id, command) -> dict | None: ...
    def reserve_recovery(self, actor, run_id, command, execution) -> tuple[dict, bool]: ...
