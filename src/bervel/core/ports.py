from typing import Any, Protocol
from uuid import UUID

from .models import (ActorContext, ArtifactRevisionRef, RegisterArtifact, StoredObject,
                     DatasetRevisionRef, ExtractArtifact, ExtractionResult)


class ObjectStore(Protocol):
    def put(self, content: bytes) -> StoredObject: ...
    def read(self, object_ref: str) -> bytes: ...


class ArtifactRepository(Protocol):
    def register_artifact(self, actor: ActorContext, command: RegisterArtifact, stored: StoredObject) -> ArtifactRevisionRef: ...
    def read_artifact(self, actor: ActorContext, ref: ArtifactRevisionRef) -> dict[str, Any]: ...
    def artifact_history(self, actor: ActorContext, artifact_id: UUID) -> dict[str, Any]: ...


class DatasetRepository(Protocol):
    def publish_extraction(self, actor: ActorContext, command: ExtractArtifact, result: ExtractionResult,
                           producer: dict[str, str]) -> DatasetRevisionRef: ...
    def read_dataset(self, actor: ActorContext, ref: DatasetRevisionRef) -> dict[str, Any]: ...
    def read_records(self, actor: ActorContext, ref: DatasetRevisionRef, cursor: int, limit: int) -> dict[str, Any]: ...
