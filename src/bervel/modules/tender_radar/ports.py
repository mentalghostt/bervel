"""Dependencies required by tender radar, implemented by outer adapters."""
from typing import ContextManager, Protocol
from uuid import UUID

from bervel.core.document_models import DocumentSnapshot, DocumentSource
from bervel.core.models import ActorContext
from bervel.modules.tender_radar.models import RadarBatch, RadarReport, RadarRun, RadarRunSummary, TenderImport,StockData


class TenderImporter(Protocol):
    def parse(self, content: bytes, filename: str) -> TenderImport: ...


class StockImporter(Protocol):
    def parse(self,content:bytes,filename:str) -> 'StockData': ...


class EconomicsImporter(Protocol):
    def parse(self,content:bytes,filename:str) -> dict: ...


class RadarMemory(Protocol):
    def context(self, actor: ActorContext, snapshot: list[DocumentSnapshot], question: str, *, complete: bool = False) -> list[DocumentSource]: ...
    def images(self, actor: ActorContext, sources: list[DocumentSource]) -> list[dict]: ...


class RadarRepository(Protocol):
    def save_batch(self, actor: ActorContext, metadata: dict, data: TenderImport, key: str) -> RadarBatch: ...
    def list_batches(self, actor: ActorContext) -> list[RadarBatch]: ...
    def enqueue(self, actor: ActorContext, batch_id: UUID, snapshot: list[DocumentSnapshot], focus: str, key: str,*,selection:dict|None=None) -> RadarRun: ...
    def read(self, actor: ActorContext, run_id: UUID) -> RadarRun: ...
    def list_runs(self, actor: ActorContext) -> list[RadarRunSummary]: ...
    def batch(self, actor: ActorContext, batch_id: UUID) -> dict: ...
    def claim(self) -> ContextManager[dict | None]: ...
    def finish(self, run_id: UUID, *, report: RadarReport | None = None, model: str | None = None, error: str | None = None) -> None: ...
    def checkpoint(self,run_id:UUID,report:RadarReport,*,model:str|None=None)->None: ...
